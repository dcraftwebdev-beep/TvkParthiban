/** t("English text", { n: 3 }) gives the text in the chosen language. t.lang and t.setLang are attached. */
export const makeT = (lang, setLang) => {
  const t = (k, v) => {
    let s = lang === "ta" ? (TA[k] ?? k) : k;
    if (v) for (const key of Object.keys(v)) s = s.split("{" + key + "}").join(v[key]);
    return s;
  };
  t.lang = lang; t.setLang = setLang;
  return t;
};
